    private void btnEjecutarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEjecutarActionPerformed
        try {
        int len = Integer.parseInt(txtLongitud.getText().trim());
        if (len <= 0) {
            JOptionPane.showMessageDialog(this, "La longitud debe ser mayor a 0.");
            return;
        }

        busquedaObj = new BusquedaRecursiva(len);
        vectorActual = busquedaObj.retornarVector();

        if (modoActual == ModoBusqueda.BINARIA || modoActual == ModoBusqueda.BINARIA_LIMITES) {
            java.util.Arrays.sort(vectorActual);
        }

        dibujarVector(new ArrayList<>());

        lblResultado.setText("Resultado: ");
        lblCantidad.setText("Cantidad: ");
        
        } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Ingrese un número válido para la longitud.");
        }
    }//GEN-LAST:event_btnEjecutarActionPerformed

