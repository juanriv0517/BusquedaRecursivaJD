    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        
        if (vectorActual == null) {
            JOptionPane.showMessageDialog(this, "Primero genere el vector haciendo clic en 'Ejecutar'.");
            return;
        }

        try {
            ArrayList<Integer> coincidencias = new ArrayList<>();
            int valor = 0;

            // Leer dato a buscar solo si el método lo requiere
            if (modoActual != ModoBusqueda.MINIMO && modoActual != ModoBusqueda.MAXIMO) {
                valor = Integer.parseInt(txtDatoBuscar.getText().trim());
            }

            // Según el modo, ejecutamos el método del Back correspondiente
            switch (modoActual) {
                case SECUENCIAL -> {
                    boolean encontrado = BusquedaRecursiva.secuencial(vectorActual, 0, valor);
                    if (encontrado) {
                        int pos = busquedaObj.BuscarIndice(vectorActual, 0, valor);
                        if (pos != -1) coincidencias.add(pos);
                    }
                }

                case SECUENCIAL_INDICE -> {
                    int posInd = busquedaObj.BuscarIndice(vectorActual, 0, valor);
                    if (posInd != -1) coincidencias.add(posInd);
                }

                case BINARIA -> {
                    java.util.Arrays.sort(vectorActual);
                    int posBin = busquedaObj.buscarBinaria(vectorActual, 0, vectorActual.length - 1, valor);
                    if (posBin != -1) coincidencias.add(posBin);
                }

                case BINARIA_LIMITES -> {
                    java.util.Arrays.sort(vectorActual);
                    int posLim = busquedaObj.binariaLimites(vectorActual, 0, vectorActual.length - 1, valor);
                    if (posLim != -1) coincidencias.add(posLim);
                }

                case TODAS_OCURRENCIAS -> busquedaObj.todasLasOcurrencias(vectorActual, 0, valor, coincidencias);

                case MINIMO -> {
                    int valMin = busquedaObj.buscarMinimo(vectorActual, 0);
                    int posMin = busquedaObj.BuscarIndice(vectorActual, 0, valMin);
                    if (posMin != -1) coincidencias.add(posMin);
                    lblResultado.setText("Resultado: El elemento MÍNIMO es " + valMin);
                }

                case MAXIMO -> {
                    int valMax = busquedaObj.buscarMaximo(vectorActual, 0);
                    int posMax = busquedaObj.BuscarIndice(vectorActual, 0, valMax);
                    if (posMax != -1) coincidencias.add(posMax);
                    lblResultado.setText("Resultado: El elemento MÁXIMO es " + valMax);
                }

                case POSICION -> {
                    int posUlt = busquedaObj.buscarUltimaPosicion(vectorActual, vectorActual.length - 1, valor);
                    if (posUlt != -1) coincidencias.add(posUlt);
                }

                case AMBOS_EXTREMOS -> {
                    int posExt = busquedaObj.buscarAmbosExtremos(vectorActual, 0, vectorActual.length - 1, valor);
                    if (posExt != -1) coincidencias.add(posExt);
                }
            }

            dibujarVector(coincidencias);
            
            if (modoActual != ModoBusqueda.MINIMO && modoActual != ModoBusqueda.MAXIMO) {
                if (!coincidencias.isEmpty()) {
                    lblResultado.setText("Resultado: El dato " + valor + " existe");
                    lblCantidad.setText("Cantidad: " + coincidencias.size());
                } else {
                    lblResultado.setText("Resultado: El dato " + valor + " NO existe");
                    lblCantidad.setText("Cantidad: 0");
                }
            } else {
                lblCantidad.setText("Cantidad: " + coincidencias.size());
            }

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Ingrese un número entero válido.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void dibujarVector(ArrayList<Integer> posicionesEncontradas) {
        panelContenedorCeldas.removeAll();

        for (int i = 0; i < vectorActual.length; i++) {
            JLabel lblCelda = new JLabel(String.valueOf(vectorActual[i]), SwingConstants.CENTER);
            lblCelda.setPreferredSize(new Dimension(32, 32));
            lblCelda.setFont(new Font("SansSerif", Font.BOLD, 12));
            lblCelda.setOpaque(true);
            lblCelda.setBorder(BorderFactory.createLineBorder(Color.BLACK));

            // Si el índice coincide con una de las ocurrencias encontradas, se pinta de AMARILLO
            if (posicionesEncontradas.contains(i)) {
                lblCelda.setBackground(Color.YELLOW);
            } else {
                lblCelda.setBackground(Color.WHITE);
            }

            panelContenedorCeldas.add(lblCelda);
        }

        panelContenedorCeldas.revalidate();
        panelContenedorCeldas.repaint();
    }

